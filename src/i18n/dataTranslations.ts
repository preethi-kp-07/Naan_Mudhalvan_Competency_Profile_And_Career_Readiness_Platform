// Helper to get localized question
export function getLocalizedQuestion(q: AssessmentQuestion, lang: 'en' | 'ta'): AssessmentQuestion {
  if (lang === 'en') {
    return q;
  }
  const translated = TAMIL_ASSESSMENT_QUESTIONS[q.id];
  if (!translated) {
    return q;
  }
  return {
    ...q,
    competency: COMPETENCY_TRANSLATIONS[q.competency]?.ta || q.competency,
    difficulty: (DIFFICULTY_TRANSLATIONS[q.difficulty]?.ta || q.difficulty) as any,
    questionText: translated.questionText || q.questionText,
    options: translated.options || q.options,
    explanation: translated.explanation || q.explanation,
  };
}

